/// Looks up the original PS2/PC texel dimensions `(width, height)` for an overlay sprite sheet.
pub fn original_sheet_dimensions(sheet_name: &str) -> (u32, u32) {
    SHEET_ORIGINAL_DIMENSIONS
        .iter()
        .find(|&&(name, _)| name == sheet_name)
        .map(|&(_, dims)| dims)
        .unwrap_or((256, 256))
}

