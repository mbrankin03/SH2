use crate::cutaway::CutawayOverlayEngine;
use crate::inventory::InventoryManager;
use crate::world::{ElevatorFloor, ElevatorKind, MultiFloorElevatorPanel, PushableObjectKind};

use super::super::{EventFlags, ProgContext, PROG_KEY_A, PROG_KEY_B, PROG_KEY_DOWN, PROG_KEY_UP};
use super::ProgTickOut;

/// Bespoke interactive handlers for Act 1 Bowling, Heaven's Night & Brookhaven Hospital (`Stages 15..=27`).
#[allow(clippy::too_many_arguments)]
pub(super) fn tick_bespoke(
    p: &mut ProgContext,
    down: u32,
    flags: &mut EventFlags,
    inventory: &mut InventoryManager,
    overlay: &mut CutawayOverlayEngine,
    active_elevator: Option<&mut Option<MultiFloorElevatorPanel>>,
    out: &mut ProgTickOut,
) -> bool {
    match (p.stage, p.prog_no) {
        // Stage 19 #4: Hospital 3F carbon paper memo (`s19_carbon_number`)
        (19, 4) => {
            match p.step {
                0 => {
                    p.locked = true;
                    overlay.set_picture(Some("hsp_p_carbon"), flags);
                    p.step = 1;
                    out.finished = false;
                }
                1 => {
                    if (down & (PROG_KEY_A | PROG_KEY_B)) != 0 {
                        overlay.set_picture(None, flags);
                        p.locked = false;
                        out.finished = true;
                    } else {
                        out.finished = false;
                    }
                }
                _ => out.finished = true,
            }
            true
        }
        // Stage 20 #5: Hospital 3F wall blood symbols (`s20_guruguru_number`)
        (20, 5) => {
            match p.step {
                0 => {
                    p.locked = true;
                    overlay.set_picture(Some("hsp_p_boxnumber"), flags);
                    flags.set(203, true);
                    p.step = 1;
                    out.finished = false;
                }
                1 => {
                    if (down & (PROG_KEY_A | PROG_KEY_B)) != 0 {
                        overlay.set_picture(None, flags);
                        p.locked = false;
                        out.finished = true;
                    } else {
                        out.finished = false;
                    }
                }
                _ => out.finished = true,
            }
            true
        }
        // Stage 20 #10: Shower drain key fishing with combined Bent needle + Piece of hair (`87`)
        (20, 10) => {
            p.locked = true;
            inventory.item_lose(87);
            inventory.item_get_now(37); // Elevator key
            flags.set(210, true);
            out.sound_effects.push(0x2b21);
            p.locked = false;
            out.finished = true;
            true
        }
        // Stage 24 #2: Brookhaven Otherworld B1 Storeroom shelf push (`sh2pc.exe` `0x00588370`, `flag 223`)
        (24, 2) => {
            p.locked = true;
            if PushableObjectKind::HospitalB1StoreroomShelf.trigger_push(flags) {
                out.sound_effects.push(0x2b1b);
            } else {
                p.flag_set = false;
            }
            p.locked = false;
            out.finished = true;
            true
        }
        // Stage 18 #2 / Stage 22 #2: Brookhaven Hospital Normal / Otherworld Elevator Panels
        (18, 2) | (22, 2) => {
            let Some(slot) = active_elevator else {
                return false;
            };
            let kind = if p.stage == 18 {
                ElevatorKind::HospitalNormal
            } else {
                ElevatorKind::HospitalOtherworld
            };
            match p.step {
                0 => {
                    p.locked = true;
                    *slot = Some(MultiFloorElevatorPanel::new(
                        kind,
                        ElevatorFloor::Floor1,
                        false,
                    ));
                    p.step = 1;
                    out.finished = false;
                }
                1 => {
                    if let Some(panel) = slot.as_mut() {
                        if (down & PROG_KEY_UP) != 0 {
                            panel.move_cursor(-1);
                        } else if (down & PROG_KEY_DOWN) != 0 {
                            panel.move_cursor(1);
                        }
                    }
                    if (down & (PROG_KEY_A | PROG_KEY_B)) != 0 {
                        *slot = None;
                        p.locked = false;
                        out.finished = true;
                    } else {
                        out.finished = false;
                    }
                }
                _ => out.finished = true,
            }
            true
        }
        _ => false,
    }
}
